import ts from 'typescript'
import { CliFileWriter } from '../../cli/CliFileWriter.js'
import { IntrospectedColumn, IntrospectedTable } from '../../types/db.js'
import camelize from '../camelize.js'
import { propertyName } from './ASTBuilder.js'
import ASTConnectionBuilder from './ASTConnectionBuilder.js'
import autogeneratedFileDisclaimer from './autoGeneratedFileDisclaimer.js'
import {
  dbTypesHelperNames,
  dbTypesName,
  dbTypesReservedNames,
  HELPER_TYPE_DECLARATIONS,
  PLAIN_ARRAY_VALUE_TYPES,
} from './dbTypesNaming.js'

const f = ts.factory

/**
 * Writes a connection's types/db.ts (types/db.<connectionName>.ts for any
 * connection but default) from its introspection: the Kysely `DB`
 * interface, an interface for each table, each enum the tables use as a
 * union of its values with a `<Enum>Values` const of them, and the column
 * types those declare. Columns that the table's models ignore are left out,
 * so that code still referring to one fails to compile.
 */
export default class ASTDbTypesBuilder extends ASTConnectionBuilder {
  public async build() {
    const database = await this.introspectedDatabase()
    const enumTypeNames = await this.enumTypeNames()
    const helperNames = dbTypesHelperNames(database.tables)
    const takenNames = new Set([...dbTypesReservedNames(database.tables), ...enumTypeNames.values()])

    const tables = database.tables.map(table => ({
      key: this.tableKey(table),
      interfaceName: dbTypesName(this.tableKey(table), takenNames),
      columns: this.columns(table, enumTypeNames),
    }))

    const enumValues = new Map(database.enums.map(databaseEnum => [databaseEnum.name, databaseEnum.values]))
    const typeDeclarations = [
      ...helperNames.map(name => ({ name, statements: [helperTypeDeclaration(name)] })),
      ...[...enumTypeNames].map(([enumName, typeName]) => ({
        name: typeName,
        statements: enumDeclarations(
          typeName,
          [...(enumValues.get(enumName) ?? [])].sort((a, b) => a.localeCompare(b))
        ),
      })),
    ]

    const tableInterfaces = [...tables]
      .sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))
      .map(table =>
        f.createInterfaceDeclaration(
          [f.createModifier(ts.SyntaxKind.ExportKeyword)],
          table.interfaceName,
          undefined,
          undefined,
          table.columns.map(column =>
            f.createPropertySignature(undefined, propertyName(column.key), undefined, column.type)
          )
        )
      )

    const dbMembers = tables.map(table => ({
      name: propertyName(table.key),
      type: f.createTypeReferenceNode(table.interfaceName),
    }))

    const statements = [
      ...typeDeclarations
        .sort((a, b) => a.name.localeCompare(b.name))
        .flatMap(declaration => declaration.statements),
      ...tableInterfaces,
      f.createInterfaceDeclaration(
        [f.createModifier(ts.SyntaxKind.ExportKeyword)],
        'DB',
        undefined,
        undefined,
        dbMembers.map(member => f.createPropertySignature(undefined, member.name, undefined, member.type))
      ),
      f.createClassDeclaration(
        [f.createModifier(ts.SyntaxKind.ExportKeyword)],
        'DBClass',
        undefined,
        undefined,
        dbMembers.map(member =>
          f.createPropertyDeclaration(undefined, member.name, undefined, member.type, undefined)
        )
      ),
    ]

    const sourceFile = ts.createSourceFile('', '', ts.ScriptTarget.Latest, false, ts.ScriptKind.TS)
    const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, omitTrailingSemicolon: true })
    const print = (node: ts.Node) => printer.printNode(ts.EmitHint.Unspecified, node, sourceFile)

    const output = await this.prettier(`\
${autogeneratedFileDisclaimer()}
${this.imports(helperNames).map(print).join('\n')}

${statements.map(print).join('\n\n')}
`)

    await CliFileWriter.write(this.dbPath(), output)
  }

  /**
   * @internal
   *
   * the table's columns, minus those its models ignore, sorted by name, each
   * with its key (the camelized column name) and its type
   */
  private columns(table: IntrospectedTable, enumTypeNames: Map<string, string>) {
    const ignoredColumns = this.ignoredColumnsForTable(this.tableKey(table))

    return [...table.columns]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map(column => ({ key: camelize(column.name), type: columnType(column, enumTypeNames) }))
      .filter(column => !ignoredColumns.has(column.key))
  }

  /**
   * @internal
   *
   * the file's imports: Dream's date and time classes, Kysely's ColumnType,
   * and postgres-interval's type when a column is an interval
   */
  private imports(helperNames: string[]) {
    return [
      ...this.dateAndDateTimeImports(),
      typeImport('ColumnType', 'kysely'),
      ...(helperNames.includes('Interval') ? [typeImport('IPostgresInterval', 'postgres-interval')] : []),
    ]
  }
}

/**
 * The column's type in its table's interface: its value type (an array of
 * them for an array column), `| null` when it allows null, all wrapped in
 * `Generated<>` when an insert may leave it out.
 */
function columnType(column: IntrospectedColumn, enumTypeNames: Map<string, string>) {
  const valueType = f.createTypeReferenceNode(
    column.valueType === 'enum' ? enumTypeNames.get(column.enumName!)! : column.valueType
  )

  let type: ts.TypeNode = valueType
  if (column.isArray) {
    type = PLAIN_ARRAY_VALUE_TYPES.includes(column.valueType)
      ? f.createArrayTypeNode(valueType)
      : f.createTypeReferenceNode('ArrayType', [valueType])
  }
  if (column.allowNull) type = f.createUnionTypeNode([type, f.createLiteralTypeNode(f.createNull())])
  if (column.hasDefault) type = f.createTypeReferenceNode('Generated', [type])

  return type
}

/**
 * An enum's type, the union of its values (`never` when it has none), and
 * its `<Enum>Values` const, which lists them.
 */
function enumDeclarations(typeName: string, values: string[]) {
  const exportModifier = f.createModifier(ts.SyntaxKind.ExportKeyword)

  return [
    f.createTypeAliasDeclaration(
      [exportModifier],
      typeName,
      undefined,
      values.length
        ? f.createUnionTypeNode(values.map(value => f.createLiteralTypeNode(f.createStringLiteral(value))))
        : f.createKeywordTypeNode(ts.SyntaxKind.NeverKeyword)
    ),
    f.createVariableStatement(
      [exportModifier],
      f.createVariableDeclarationList(
        [
          f.createVariableDeclaration(
            `${typeName}Values`,
            undefined,
            undefined,
            f.createAsExpression(
              f.createArrayLiteralExpression(values.map(value => f.createStringLiteral(value))),
              f.createKeywordTypeNode(ts.SyntaxKind.ConstKeyword as ts.KeywordTypeSyntaxKind)
            )
          ),
        ],
        ts.NodeFlags.Const
      )
    ),
  ]
}

/**
 * A type types/db.ts declares for its columns, parsed from its declaration,
 * which is fixed rather than built from the database.
 */
function helperTypeDeclaration(name: string) {
  return ts.createSourceFile(
    '',
    HELPER_TYPE_DECLARATIONS[name]!,
    ts.ScriptTarget.Latest,
    false,
    ts.ScriptKind.TS
  ).statements[0]!
}

function typeImport(name: string, moduleName: string) {
  return f.createImportDeclaration(
    undefined,
    f.createImportClause(
      true,
      undefined,
      f.createNamedImports([f.createImportSpecifier(false, undefined, f.createIdentifier(name))])
    ),
    f.createStringLiteral(moduleName)
  )
}
